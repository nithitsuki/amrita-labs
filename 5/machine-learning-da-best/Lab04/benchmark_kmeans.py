"""
Lab Session 04 (23CSE301) - A3: Performance comparison of two k-means versions.

Version 1 (user):  the student's own implementation from Lab03 (a11), copied
                    verbatim below (only adapted to return centroids and count
                    iterations; the algorithm is unchanged).
Version 2 (AI):    the AI-generated numpy-vectorized kmeans from lab04.py,
                    generated by DeepSeek-V4-Flash-0731 (via custom pi harness).

Protocol
--------
- Synthetic Gaussian-blob data with a fixed seed (identical for both versions).
- Identical initialization: first k points as centroids (same as Lab03 a11).
- Identical metric: Euclidean distance.
- Identical stopping rule: stop when no centroid changes.
- Each case runs 3 times; the minimum wall time is reported per version.
- Iteration counts and the centroid agreement come from the repeat with the
  minimum user wall time, so both versions are compared on identical data
  (on identical data the two versions always converge with equal iterations
  and identical centroids).
"""

import csv
import importlib.util
import os
import sys
import time

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

# ---------------------------------------------------------------------------
# Version 1: the student's own k-means (verbatim adaptation of Lab03 a11)
# ---------------------------------------------------------------------------


def euc_len(a):
    """Euclidean norm helper used by the user's k-means (copied from Lab03)."""
    # Copied verbatim from Lab03/lab03.py (student's own work).
    s = 0
    for v in a:
        s += v * v
    return s ** 0.5


def kmeans_user(k, points):
    """
    Verbatim adaptation of the student's Lab03 a11 (own-work version).

    The only mechanical changes are:
      1. it returns the centroids instead of printing them,
      2. it counts the iterations.
    The algorithm itself is unchanged.
    """
    # Verbatim adaptation of the student's Lab03 a11 (own-work version).
    centroids = []
    for i in range(k):
        centroids.append(list(points[i]))
    # loop
    centroids_changed = True
    iterations = 0
    while centroids_changed:
        iterations += 1
        # step 1: assign every point to its nearest centroid
        clusters = []
        for _ in range(k):
            clusters.append([])
        for p in points:
            dists = []
            for c in centroids:
                diffs = []
                for a, b in zip(p, c):
                    diffs.append(a - b)
                dists.append(euc_len(diffs))
            nearest = dists.index(min(dists))
            clusters[nearest].append(p)

        # step 2: recompute each centroid as the mean of its cluster
        new_centroids = []
        for cluster in clusters:
            n = len(cluster)
            avg = []
            for i in range(len(cluster[0])):
                total = 0
                for v in cluster:
                    total += v[i]
                avg.append(total / n)
            new_centroids.append(avg)
        centroids_changed = centroids != new_centroids
        centroids = new_centroids
    # final
    return centroids, iterations


