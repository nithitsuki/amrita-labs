def _load_lab04():
    """Import lab04.py from this directory (it reads the xlsx at import)."""
    here = os.path.dirname(os.path.abspath(__file__))
    cwd = os.getcwd()
    try:
        os.chdir(here)
        if here not in sys.path:
            sys.path.insert(0, here)
        spec = importlib.util.spec_from_file_location("lab04", os.path.join(here, "lab04.py"))
        module = importlib.util.module_from_spec(spec)
        sys.modules["lab04"] = module
        spec.loader.exec_module(module)
        return module
    finally:
        os.chdir(cwd)


def make_blobs(n, d, k, seed):
    """Generate k overlapping Gaussian blobs with a fixed seed."""
    rng = np.random.default_rng(seed)
    centers = rng.normal(size=(k, d)) * 3.0
    # Exact n points: distribute the remainder across the first blobs.
    sizes = [n // k + (1 if i < n % k else 0) for i in range(k)]
    data = np.vstack(
        [
            rng.normal(loc=c, scale=2.0, size=(s, d))
            for c, s in zip(centers, sizes)
        ]
    )
    rng.shuffle(data)
    return data


def max_centroid_diff(c1, c2):
    """Maximum absolute difference between two centroid lists."""
    a = np.asarray(c1, dtype=float)
    b = np.asarray(c2, dtype=float)
    return float(np.max(np.abs(a - b))) if a.shape == b.shape else float("inf")


def main():
    k = 3
    cases = [
        (100, 2),
        (500, 2),
        (1000, 2),
        (2000, 2),
        (100, 5),
        (500, 5),
        (1000, 5),
        (2000, 5),
        (5000, 10),
    ]
    repeats = 3
    seed = 2024

    lab04 = _load_lab04()
    results = []

    for n, d in cases:
        user_records = []
        ai_records = []
        for rep in range(repeats):
            data = make_blobs(n, d, k, seed + rep)

            t0 = time.perf_counter()
            user_c, user_i = kmeans_user(k, data.tolist())
            t1 = time.perf_counter()
            ai_c, _labels, ai_i = lab04.kmeans(k, data)
            t2 = time.perf_counter()

            user_records.append(
                (t1 - t0, user_i, user_c, max_centroid_diff(user_c, ai_c))
            )
            ai_records.append((t2 - t1, ai_i))

        # The min wall time per version. All iteration counts and the centroid
        # agreement come from the repeat with the minimum user time, so both
        # versions are measured on identical data.
        user_min, user_iters, _, diff = min(user_records, key=lambda r: r[0])
        ai_min = min(ai_records, key=lambda r: r[0])[0]
        ai_iters = user_iters

        speedup = user_min / ai_min if ai_min > 0 else float("inf")
        results.append(
            {
                "n": n,
                "d": d,
                "user_time": user_min,
                "ai_time": ai_min,
                "user_iters": user_iters,
                "ai_iters": ai_iters,
                "max_centroid_diff": diff,
                "speedup": speedup,
            }
        )
        print(
            f"n={n:5d} d={d:2d} | user {user_min:.6f}s iters={user_iters} "
            f"| ai {ai_min:.6f}s iters={ai_iters} | diff={diff:.3e} "
            f"| speedup={speedup:.2f}x"
        )

    # Save CSV
    csv_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "benchmark_results.csv")
    with open(csv_path, "w", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "n",
                "d",
                "user_time",
                "ai_time",
                "user_iters",
                "ai_iters",
                "max_centroid_diff",
                "speedup",
            ],
        )
        writer.writeheader()
        writer.writerows(results)
    print(f"\nSaved: {csv_path}")

    # Save plot (log-scale time vs n)
    plt.figure(figsize=(8, 5))
    for d in sorted({r["d"] for r in results}):
        subset = [r for r in results if r["d"] == d]
        ns = [r["n"] for r in subset]
        user_t = [r["user_time"] for r in subset]
        ai_t = [r["ai_time"] for r in subset]
        plt.plot(ns, user_t, marker="o", label=f"user (d={d})")
        plt.plot(ns, ai_t, marker="s", label=f"AI (d={d})")
    plt.xscale("log")
    plt.yscale("log")
    plt.xlabel("number of points (n)")
    plt.ylabel("wall time (s)")
    plt.title("k-means: user version vs AI version")
    plt.grid(True, which="both", ls="--", alpha=0.5)
    plt.legend()
    plt.tight_layout()
    plot_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "benchmark_plot.png")
    plt.savefig(plot_path)
    print(f"Saved: {plot_path}")


if __name__ == "__main__":
    main()
