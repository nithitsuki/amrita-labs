# Function definition by the student; body generated by DeepSeek-V4-Flash-0731
# (via custom pi harness) - "vectorize k-NN with numpy broadcasting and
# per-batch argsort, tie-break with stable sort"
def genai_knn(X_train, y_train, X_test, k=3, chunk=64):
    X_train = np.asarray(X_train, dtype=float)
    X_test = np.asarray(X_test, dtype=float)
    y_train = np.asarray(y_train)
    preds = []
    for start in range(0, len(X_test), chunk):
        batch = X_test[start:start + chunk]
        dists = ((batch[:, None, :] - X_train[None, :, :]) ** 2).sum(axis=2)
        order = np.argsort(dists, axis=1, kind="stable")[:, :k]
        labels = y_train[order]
        for row in labels:
            counts = np.bincount(row)
            preds.append(counts.argmax())
    return np.asarray(preds)


