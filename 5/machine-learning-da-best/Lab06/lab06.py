# "A3: benchmark three k-NN versions - accuracy, precision, recall, f1 and
# average wall time of 10 runs; tabulate to CSV and plot"
def a10(X_train, X_test, y_train, y_test):
    print("\nA10. performance comparison of 3 k-NN versions")
    versions = {
        "mine": lambda: KNN(k=3).fit(X_train, y_train).predict(X_test),
        "sklearn": lambda: KNeighborsClassifier(n_neighbors=3).fit(X_train, y_train).predict(X_test),
        "genai": lambda: genai_knn(X_train, y_train, X_test, k=3),
    }
    rows = []
    for name, fn in versions.items():
        preds = fn()
        acc = accuracy_score(y_test, preds)
        prec = precision_score(y_test, preds)
        rec = recall_score(y_test, preds)
        f1 = f1_score(y_test, preds)
        times = []
        for _ in range(10):
            t0 = time.perf_counter()
            fn()
            times.append(time.perf_counter() - t0)
        avg_time = sum(times) / len(times)
        rows.append([name, round(acc, 4), round(prec, 4), round(rec, 4), round(f1, 4), round(avg_time, 4)])
        print("%-8s acc=%.4f prec=%.4f rec=%.4f f1=%.4f time=%.4fs" % (name, acc, prec, rec, f1, avg_time))
    table = pd.DataFrame(rows, columns=["version", "accuracy", "precision", "recall", "f1", "avg_time"])
    table.to_csv("benchmark_lab06_results.csv", index=False)
    print("saved benchmark_lab06_results.csv")
    plt.figure(figsize=(10, 4))
    plt.subplot(1, 2, 1)
    metrics = ["accuracy", "precision", "recall", "f1"]
    x = np.arange(len(metrics))
    width = 0.25
    for i, name in enumerate(versions):
        plt.bar(x + i * width, [rows[i][j + 1] for j in range(4)], width, label=name)
    plt.xticks(x + width, metrics)
    plt.ylabel("score")
    plt.legend()
    plt.grid(axis="y")
    plt.subplot(1, 2, 2)
    plt.bar([r[0] for r in rows], [r[5] for r in rows])
    plt.ylabel("avg time (s)")
    plt.yscale("log")
    plt.grid(axis="y")
    plt.tight_layout()
    plt.savefig("benchmark_lab06.png")
    print("saved benchmark_lab06.png")


